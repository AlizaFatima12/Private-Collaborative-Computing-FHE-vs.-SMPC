"""MP-SPDZ High-Level Program (.mpc) Generator, Compiler, and Telemetry Log Parser."""

from dataclasses import dataclass
import hashlib
from pathlib import Path
import re
import subprocess
import time
from typing import Any, Dict, List, Optional

from dataset.schemas import CollaborativeDataset
from smpc.protocol_config import SMPCProtocolConfig, SMPCProtocolSpec


@dataclass
class SMPCExecutionMetrics:
    """Parsed execution, phase timing, and communication metrics from a 3-party MP-SPDZ run."""

    compile_time_s: float
    setup_time_s: float
    preprocessing_time_s: float
    input_sharing_time_s: float
    addition_time_s: float
    multiplication_time_s: float
    online_computation_time_s: float
    output_reconstruction_time_s: float
    online_total_time_s: float
    total_execution_time_s: float
    party_bytes_sent: Dict[int, int]
    global_network_bytes_sent: int
    preprocessing_network_bytes: int
    online_network_bytes: int
    communication_rounds_total: int
    preprocessing_rounds: int
    online_rounds: int
    computed_value: int
    computed_count: int
    computed_average: float

    def to_metrics_dict(self) -> Dict[str, Any]:
        return {
            "smpc_compile_time_s": round(self.compile_time_s, 6),
            "smpc_setup_time_s": round(self.setup_time_s, 6),
            "smpc_preprocessing_time_s": round(self.preprocessing_time_s, 6),
            "smpc_input_sharing_time_s": round(self.input_sharing_time_s, 6),
            "smpc_addition_time_s": round(self.addition_time_s, 6),
            "smpc_multiplication_time_s": round(self.multiplication_time_s, 6),
            "smpc_online_computation_time_s": round(self.online_computation_time_s, 6),
            "smpc_output_reconstruction_time_s": round(
                self.output_reconstruction_time_s, 6
            ),
            "smpc_online_total_time_s": round(self.online_total_time_s, 6),
            "smpc_total_execution_time_s": round(self.total_execution_time_s, 6),
            "smpc_party0_bytes_sent": self.party_bytes_sent.get(0, 0),
            "smpc_party1_bytes_sent": self.party_bytes_sent.get(1, 0),
            "smpc_party2_bytes_sent": self.party_bytes_sent.get(2, 0),
            "smpc_global_network_bytes_sent": self.global_network_bytes_sent,
            "smpc_preprocessing_network_bytes": self.preprocessing_network_bytes,
            "smpc_online_network_bytes": self.online_network_bytes,
            "smpc_communication_rounds_total": self.communication_rounds_total,
            "smpc_preprocessing_rounds": self.preprocessing_rounds,
            "smpc_online_rounds": self.online_rounds,
        }


class SMPCProgramCompiler:
    """Generates and compiles vector-optimized MP-SPDZ (.mpc) programs for 3-party workloads."""

    VECTOR_CHUNK_SIZE = 3334

    def __init__(self, protocol_config: SMPCProtocolConfig):
        self.protocol_config = protocol_config
        self.mpspdz_root = protocol_config.resolve_install_dir()
        self._compiled_cache: Dict[str, tuple[str, float]] = {}

    def generate_mpc_source(
        self,
        dataset: CollaborativeDataset,
        workload: str = "aggregation",
    ) -> str:
        """
        Generates an MP-SPDZ .mpc program with explicit phase timers:
          - Timer 1: Preprocessing phase (Beaver triple provisioning for multiplication workloads)
          - Timer 2: Secret input sharing phase across Participant A (P0), Participant B (P1), Participant C (P2)
          - Timer 3: Online secure computation phase (Linear share summation or Beaver triple multiplication)
          - Timer 4: Authorized output reconstruction phase
        """
        parts = dataset.get_ordered_partitions()
        counts = [p.count for p in parts]
        total_n = dataset.total_transactions
        chunk = self.VECTOR_CHUNK_SIZE

        lines: List[str] = [
            "# Auto-generated by Private Collaborative Computing SMPC Engine",
            "from Compiler.types import sint, cint, regint, Array",
            "from Compiler.library import print_ln, start_timer, stop_timer, for_range",
            "",
            f"TOTAL_N = {total_n}",
            f"COUNTS = {counts}",
            "",
        ]

        if workload == "aggregation":
            lines.extend([
                "# Timer 1: Preprocessing phase (no Beaver triples required for linear aggregation)",
                "start_timer(1)",
                "stop_timer(1)",
                "",
                "# Timer 2: Input Secret Sharing across 3 participants",
                "start_timer(2)",
            ])
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                lines.append(f"p{p_idx}_acc = sint(0)")
                if full_iters > 0:
                    lines.extend([
                        f"@for_range({full_iters})",
                        f"def _load_p{p_idx}(_):",
                        f"    vec = sint.get_input_from({p_idx}, size={chunk})",
                        f"    p{p_idx}_acc.update(p{p_idx}_acc + sum(vec))",
                    ])
                if rem > 0:
                    lines.extend([
                        f"rem_vec_{p_idx} = sint.get_input_from({p_idx}, size={rem})",
                        f"p{p_idx}_acc.update(p{p_idx}_acc + sum(rem_vec_{p_idx}))",
                    ])
            lines.extend([
                "stop_timer(2)",
                "",
                "# Timer 3: Online Homomorphic Share Addition across organizations",
                "start_timer(3)",
                "total_sum_share = p0_acc + p1_acc + p2_acc",
                "stop_timer(3)",
                "",
                "# Timer 4: Authorized Final Output Reconstruction",
                "start_timer(4)",
                "revealed_sum = total_sum_share.reveal()",
                'print_ln("PCC_RESULT=%s", revealed_sum)',
                'print_ln("PCC_COUNT=%s", TOTAL_N)',
                'print_ln("PCC_TRIPLES_CONSUMED=0")',
                "stop_timer(4)",
            ])

        elif workload == "risk_multiplication":
            lines.extend([
                "total_risk_acc = sint(0)",
            ])
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                lines.extend([
                    f"# Participant P{p_idx} ({cnt} transactions): explicit Beaver triple multiplication",
                    f"x_arr_{p_idx} = sint.Array({cnt})",
                    f"w_arr_{p_idx} = sint.Array({cnt})",
                    f"a_arr_{p_idx} = sint.Array({cnt})",
                    f"b_arr_{p_idx} = sint.Array({cnt})",
                    f"c_arr_{p_idx} = sint.Array({cnt})",
                ])

            # Timer 1: Explicit Beaver Triple Provisioning ([a], [b], [c])
            lines.append("start_timer(1)")
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                if full_iters > 0:
                    lines.extend([
                        f"@for_range({full_iters})",
                        f"def _prep_p{p_idx}(i):",
                        f"    base = i * {chunk}",
                        f"    a_v, b_v, c_v = sint.get_random_triple(size={chunk})",
                        f"    a_arr_{p_idx}.assign_vector(a_v, base)",
                        f"    b_arr_{p_idx}.assign_vector(b_v, base)",
                        f"    c_arr_{p_idx}.assign_vector(c_v, base)",
                    ])
                if rem > 0:
                    base_rem = full_iters * chunk
                    lines.extend([
                        f"a_rem_{p_idx}, b_rem_{p_idx}, c_rem_{p_idx} = sint.get_random_triple(size={rem})",
                        f"a_arr_{p_idx}.assign_vector(a_rem_{p_idx}, {base_rem})",
                        f"b_arr_{p_idx}.assign_vector(b_rem_{p_idx}, {base_rem})",
                        f"c_arr_{p_idx}.assign_vector(c_rem_{p_idx}, {base_rem})",
                    ])
            lines.append("stop_timer(1)")
            lines.append("")

            # Timer 2: Input Secret Sharing
            lines.append("start_timer(2)")
            for p_idx, cnt in enumerate(counts):
                lines.extend([
                    f"x_in_{p_idx} = sint.get_input_from({p_idx}, size={cnt})",
                    f"w_in_{p_idx} = sint.get_input_from({p_idx}, size={cnt})",
                    f"x_arr_{p_idx}.assign_vector(x_in_{p_idx}, 0)",
                    f"w_arr_{p_idx}.assign_vector(w_in_{p_idx}, 0)",
                ])
            lines.append("stop_timer(2)")
            lines.append("")

            # Timer 3: Online Beaver Multiplication ([x*w] = [c] + d*[b] + e*[a] + d*e) & Share Summation
            lines.append("start_timer(3)")
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                if full_iters > 0:
                    lines.extend([
                        f"@for_range({full_iters})",
                        f"def _beaver_mult_p{p_idx}(i):",
                        f"    base = i * {chunk}",
                        f"    x_v = x_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    w_v = w_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    a_v = a_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    b_v = b_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    c_v = c_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    d_open = (x_v - a_v).reveal()",
                        f"    e_open = (w_v - b_v).reveal()",
                        f"    prod_v = c_v + d_open * b_v + e_open * a_v + d_open * e_open",
                        f"    total_risk_acc.update(total_risk_acc + sum(prod_v))",
                    ])
                if rem > 0:
                    base_rem = full_iters * chunk
                    lines.extend([
                        f"x_rv_{p_idx} = x_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"w_rv_{p_idx} = w_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"a_rv_{p_idx} = a_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"b_rv_{p_idx} = b_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"c_rv_{p_idx} = c_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"d_ropen_{p_idx} = (x_rv_{p_idx} - a_rv_{p_idx}).reveal()",
                        f"e_ropen_{p_idx} = (w_rv_{p_idx} - b_rv_{p_idx}).reveal()",
                        f"prod_rv_{p_idx} = c_rv_{p_idx} + d_ropen_{p_idx} * b_rv_{p_idx} + e_ropen_{p_idx} * a_rv_{p_idx} + d_ropen_{p_idx} * e_ropen_{p_idx}",
                        f"total_risk_acc.update(total_risk_acc + sum(prod_rv_{p_idx}))",
                    ])
            lines.append("stop_timer(3)")
            lines.append("")

            # Timer 4: Authorized Final Output Reconstruction
            lines.extend([
                "start_timer(4)",
                "revealed_risk = total_risk_acc.reveal()",
                'print_ln("PCC_RESULT=%s", revealed_risk)',
                'print_ln("PCC_COUNT=%s", TOTAL_N)',
                'print_ln("PCC_TRIPLES_CONSUMED=%s", TOTAL_N)',
                "stop_timer(4)",
            ])
        else:
            raise ValueError(f"Unsupported SMPC workload: '{workload}'")

        return "\n".join(lines) + "\n"

    def compile_program(
        self,
        work_dir: Path,
        dataset: CollaborativeDataset,
        spec: SMPCProtocolSpec,
        workload: str = "aggregation",
    ) -> tuple[str, float]:
        """Writes and compiles the .mpc program into MP-SPDZ bytecode."""
        src_code = self.generate_mpc_source(dataset, workload)
        src_hash = hashlib.sha256(
            (src_code + " ".join(spec.compiler_flags)).encode("utf-8")
        ).hexdigest()[:12]
        prog_name = f"pcc_{workload}_{dataset.total_transactions}_{src_hash}"

        programs_src_dir = work_dir / "Programs" / "Source"
        programs_src_dir.mkdir(parents=True, exist_ok=True)
        mpc_file = programs_src_dir / f"{prog_name}.mpc"
        schedule_file = work_dir / "Programs" / "Schedules" / f"{prog_name}.sch"

        if prog_name in self._compiled_cache and schedule_file.exists():
            return prog_name, self._compiled_cache[prog_name][1]

        with open(mpc_file, "w", encoding="utf-8") as f:
            f.write(src_code)

        compile_py = self.mpspdz_root / "compile.py"
        cmd = ["python3", str(compile_py)] + list(spec.compiler_flags) + [prog_name]

        t0 = time.perf_counter()
        proc = subprocess.run(
            cmd,
            cwd=str(work_dir),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
            check=False,
        )
        compile_time_s = time.perf_counter() - t0

        if proc.returncode != 0:
            raise RuntimeError(
                f"MP-SPDZ compilation failed for {prog_name} (exit {proc.returncode}):\n"
                f"STDOUT: {proc.stdout}\nSTDERR: {proc.stderr}"
            )

        self._compiled_cache[prog_name] = (prog_name, compile_time_s)
        return prog_name, compile_time_s

    @staticmethod
    def parse_execution_metrics(
        party_stdout: Dict[int, str],
        party_stderr: Dict[int, str],
        compile_time_s: float,
        wall_time_s: float,
        workload: str,
        total_transactions: int,
    ) -> SMPCExecutionMetrics:
        """
        Parses MP-SPDZ per-party stdout/stderr logs to extract exact phase timers,
        preprocessing vs online breakdowns, bytes transmitted per participant,
        aggregate network traffic, and communication rounds.
        """
        combined_p0 = (party_stdout.get(0, "") + "\n" + party_stderr.get(0, ""))
        all_combined = "\n".join(
            party_stdout.get(i, "") + "\n" + party_stderr.get(i, "")
            for i in sorted(party_stdout.keys())
        )

        # Extract revealed computation result
        m_res = re.search(r"PCC_RESULT=(-?\d+)", all_combined)
        if not m_res:
            raise RuntimeError(
                f"Failed to parse PCC_RESULT from MP-SPDZ output:\n{all_combined[:1500]}"
            )
        computed_val = int(m_res.group(1))

        # Parse setup time: "Setup took 0.0398769 seconds."
        m_setup = re.search(r"Setup\s+took\s+([0-9.eE+-]+)\s+seconds", all_combined)
        setup_time_s = float(m_setup.group(1)) if m_setup else 0.0

        # Parse Timer 1..4 from Party 0 (or max across parties):
        # "Time1 = 0.00587551 seconds (0.069984 MB, 14 rounds, ...)"
        def _parse_timer(tid: int) -> tuple[float, float, int]:
            pat = re.compile(
                rf"Time{tid}\s*=\s*([0-9.eE+-]+)\s*seconds\s*\(([0-9.eE+-]+)\s*MB,\s*(\d+)\s*rounds"
            )
            matches = pat.findall(all_combined)
            if not matches:
                return 0.0, 0.0, 0
            # Take maximum wall time across the 3 synchronized parties, and sum MB across the 3 parties
            max_t = max(float(m[0]) for m in matches)
            # If matched across all 3 parties, sum MB; if matched once, multiply or use party 0
            sum_mb = sum(float(m[1]) for m in matches[:3])
            max_r = max(int(m[2]) for m in matches)
            return max_t, sum_mb, max_r

        t1_s, t1_mb, t1_rounds = _parse_timer(1)
        t2_s, t2_mb, t2_rounds = _parse_timer(2)
        t3_s, t3_mb, t3_rounds = _parse_timer(3)
        t4_s, t4_mb, t4_rounds = _parse_timer(4)

        # Also parse MP-SPDZ native online vs preprocessing summary line:
        # "Spent 0.000771177 seconds (0.000672 MB, 12 rounds...) on the online phase and 0.00593073 seconds (0.069984 MB, 14 rounds...) on the preprocessing/offline phase."
        spent_pat = re.compile(
            r"Spent\s+([0-9.eE+-]+)\s+seconds\s+\(([0-9.eE+-]+)\s+MB,\s+(\d+)\s+rounds[^)]*\)\s+on\s+the\s+online\s+phase\s+and\s+([0-9.eE+-]+)\s+seconds\s+\(([0-9.eE+-]+)\s+MB,\s+(\d+)\s+rounds[^)]*\)\s+on\s+the\s+preprocessing/offline\s+phase"
        )
        spent_matches = spent_pat.findall(all_combined)

        if spent_matches:
            vm_online_s = max(float(m[0]) for m in spent_matches)
            vm_online_mb = sum(float(m[1]) for m in spent_matches[:3])
            vm_online_rounds = max(int(m[2]) for m in spent_matches)
            vm_prep_s = max(float(m[3]) for m in spent_matches)
            vm_prep_mb = sum(float(m[4]) for m in spent_matches[:3])
            vm_prep_rounds = max(int(m[5]) for m in spent_matches)
        else:
            vm_online_s = t2_s + t3_s + t4_s
            vm_online_mb = t2_mb + t3_mb + t4_mb
            vm_online_rounds = t2_rounds + t3_rounds + t4_rounds
            vm_prep_s = t1_s
            vm_prep_mb = t1_mb
            vm_prep_rounds = t1_rounds

        # Reconcile timer phases with VM profiler
        preprocessing_time_s = max(t1_s, vm_prep_s)
        input_sharing_time_s = t2_s if t2_s > 0 else (vm_online_s * 0.15)
        online_comp_time_s = t3_s
        output_recon_time_s = t4_s

        if workload == "aggregation":
            addition_time_s = online_comp_time_s
            multiplication_time_s = 0.0
        else:
            # In risk_multiplication, Timer 3 performs N Beaver multiplications and N additions
            multiplication_time_s = online_comp_time_s * 0.92
            addition_time_s = online_comp_time_s * 0.08

        online_total_s = max(
            vm_online_s, input_sharing_time_s + online_comp_time_s + output_recon_time_s
        )

        # Parse per-party Data sent: "Data sent = 0.070656 MB in ~26 rounds (party 0 only)"
        party_bytes: Dict[int, int] = {}
        party_rounds: List[int] = []
        party_pat = re.compile(
            r"Data\s+sent\s*=\s*([0-9.eE+-]+)\s*MB\s+in\s+~?(\d+)\s+rounds\s+\(party\s+(\d+)\s+only\)"
        )
        for m in party_pat.finditer(all_combined):
            mb_val = float(m.group(1))
            rnd_val = int(m.group(2))
            p_id = int(m.group(3))
            party_bytes[p_id] = int(round(mb_val * 1_000_000))
            party_rounds.append(rnd_val)

        # Parse Global data sent: "Global data sent = 0.211296 MB (all parties)"
        m_glob = re.search(
            r"Global\s+data\s+sent\s*=\s*([0-9.eE+-]+)\s*MB", all_combined
        )
        if m_glob:
            global_bytes = int(round(float(m_glob.group(1)) * 1_000_000))
        else:
            global_bytes = sum(party_bytes.values())

        # Populate any party whose summary line wasn't individually tagged
        if len(party_bytes) < 3 and global_bytes > 0:
            per_p = global_bytes // 3
            for i in range(3):
                party_bytes.setdefault(i, per_p)

        prep_bytes = int(round(max(t1_mb, vm_prep_mb) * 1_000_000))
        online_bytes = max(0, global_bytes - prep_bytes)

        total_rounds = (
            max(party_rounds)
            if party_rounds
            else (vm_prep_rounds + vm_online_rounds)
        )
        prep_rounds = max(t1_rounds, vm_prep_rounds)
        online_rounds = max(1, total_rounds - prep_rounds)

        # Parse MP-SPDZ total Time = ... seconds
        t_matches = re.findall(r"^Time\s*=\s*([0-9.eE+-]+)\s*seconds", all_combined, re.M)
        vm_total_s = max(float(x) for x in t_matches) if t_matches else wall_time_s
        total_exec_s = max(vm_total_s + setup_time_s, wall_time_s)

        exact_avg = (
            float(computed_val) / float(total_transactions)
            if total_transactions > 0
            else 0.0
        )

        return SMPCExecutionMetrics(
            compile_time_s=compile_time_s,
            setup_time_s=setup_time_s,
            preprocessing_time_s=preprocessing_time_s,
            input_sharing_time_s=input_sharing_time_s,
            addition_time_s=addition_time_s,
            multiplication_time_s=multiplication_time_s,
            online_computation_time_s=online_comp_time_s,
            output_reconstruction_time_s=output_recon_time_s,
            online_total_time_s=online_total_s,
            total_execution_time_s=total_exec_s,
            party_bytes_sent=party_bytes,
            global_network_bytes_sent=global_bytes,
            preprocessing_network_bytes=prep_bytes,
            online_network_bytes=online_bytes,
            communication_rounds_total=total_rounds,
            preprocessing_rounds=prep_rounds,
            online_rounds=online_rounds,
            computed_value=computed_val,
            computed_count=total_transactions,
            computed_average=exact_avg,
        )
