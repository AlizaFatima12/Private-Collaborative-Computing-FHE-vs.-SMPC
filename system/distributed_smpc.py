"""Distributed MP-SPDZ Program Generator, Bytecode Packager, and Telemetry Parser."""

import hashlib
from pathlib import Path
import re
import subprocess
import time
from typing import Any, Dict, List

from smpc.protocol_config import SMPCProtocolConfig, SMPCProtocolSpec
from system.crypto_serialization import b64_encode, sha256_short


class DistributedSMPCCompiler:
    """Compiles .mpc programs on the Coordinator without ever touching client raw inputs."""

    VECTOR_CHUNK_SIZE = 3334

    def __init__(self, protocol_config: SMPCProtocolConfig | None = None):
        self.protocol_config = protocol_config or SMPCProtocolConfig()
        self.mpspdz_root = self.protocol_config.resolve_install_dir()
        self._cache: Dict[str, tuple[str, float, Dict[str, str]]] = {}

    @classmethod
    def generate_mpc_source(
        cls,
        counts: List[int],
        workload: str,
    ) -> str:
        """Generates a vectorized N-party .mpc program for the requested collaborative query."""
        if len(counts) < 2:
            raise ValueError(f"At least 2 organizations are required; got {len(counts)}")

        n_parties = len(counts)
        total_n = sum(counts)
        chunk = cls.VECTOR_CHUNK_SIZE
        lines: List[str] = [
            "# Auto-generated by Distributed Private Collaborative Computing System",
            "from Compiler.types import sint",
            "from Compiler.library import print_ln, start_timer, stop_timer, for_range",
            "",
            f"TOTAL_N = {total_n}",
            "",
        ]

        if workload == "aggregation":
            lines.extend(["start_timer(1)", "stop_timer(1)", "", "start_timer(2)"])
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                lines.append(f"p{p_idx}_acc = sint(0)")
                if full_iters > 0:
                    lines.extend([
                        f"@for_range({full_iters})",
                        f"def _load_p{p_idx}(_):",
                        f"    vec = sint.get_input_from({p_idx}, size={chunk})",
                        f"    p{p_idx}_acc.update(p{p_idx}_acc + sum(vec))",
                    ])
                if rem > 0:
                    lines.extend([
                        f"rem_vec_{p_idx} = sint.get_input_from({p_idx}, size={rem})",
                        f"p{p_idx}_acc.update(p{p_idx}_acc + sum(rem_vec_{p_idx}))",
                    ])
            sum_expr = " + ".join(f"p{i}_acc" for i in range(n_parties))
            lines.extend([
                "stop_timer(2)",
                "",
                "start_timer(3)",
                f"total_sum_share = {sum_expr}",
                "stop_timer(3)",
                "",
                "start_timer(4)",
                "revealed_sum = total_sum_share.reveal()",
                'print_ln("PCC_RESULT=%s", revealed_sum)',
                'print_ln("PCC_RESULT2=0")',
                'print_ln("PCC_COUNT=%s", TOTAL_N)',
                'print_ln("PCC_TRIPLES_CONSUMED=0")',
                "stop_timer(4)",
            ])

        elif workload == "filtered_aggregation":
            lines.extend(["start_timer(1)", "stop_timer(1)", "", "start_timer(2)"])
            for p_idx, cnt in enumerate(counts):
                lines.extend([
                    f"x_in_{p_idx} = sint.get_input_from({p_idx}, size={cnt})",
                    f"m_in_{p_idx} = sint.get_input_from({p_idx}, size={cnt})",
                    f"p{p_idx}_x = sum(x_in_{p_idx})",
                    f"p{p_idx}_m = sum(m_in_{p_idx})",
                ])
            fx_expr = " + ".join(f"p{i}_x" for i in range(n_parties))
            fm_expr = " + ".join(f"p{i}_m" for i in range(n_parties))
            lines.extend([
                "stop_timer(2)",
                "",
                "start_timer(3)",
                f"total_fx = {fx_expr}",
                f"total_fm = {fm_expr}",
                "stop_timer(3)",
                "",
                "start_timer(4)",
                "rev_fx = total_fx.reveal()",
                "rev_fm = total_fm.reveal()",
                'print_ln("PCC_RESULT=%s", rev_fx)',
                'print_ln("PCC_RESULT2=%s", rev_fm)',
                'print_ln("PCC_COUNT=%s", TOTAL_N)',
                'print_ln("PCC_TRIPLES_CONSUMED=0")',
                "stop_timer(4)",
            ])

        elif workload == "risk_multiplication":
            lines.append("total_risk_acc = sint(0)")
            for p_idx, cnt in enumerate(counts):
                lines.extend([
                    f"x_arr_{p_idx} = sint.Array({cnt})",
                    f"w_arr_{p_idx} = sint.Array({cnt})",
                    f"a_arr_{p_idx} = sint.Array({cnt})",
                    f"b_arr_{p_idx} = sint.Array({cnt})",
                    f"c_arr_{p_idx} = sint.Array({cnt})",
                ])
            lines.append("start_timer(1)")
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                if full_iters > 0:
                    lines.extend([
                        f"@for_range({full_iters})",
                        f"def _prep_p{p_idx}(i):",
                        f"    base = i * {chunk}",
                        f"    a_v, b_v, c_v = sint.get_random_triple(size={chunk})",
                        f"    a_arr_{p_idx}.assign_vector(a_v, base)",
                        f"    b_arr_{p_idx}.assign_vector(b_v, base)",
                        f"    c_arr_{p_idx}.assign_vector(c_v, base)",
                    ])
                if rem > 0:
                    base_rem = full_iters * chunk
                    lines.extend([
                        f"a_rem_{p_idx}, b_rem_{p_idx}, c_rem_{p_idx} = sint.get_random_triple(size={rem})",
                        f"a_arr_{p_idx}.assign_vector(a_rem_{p_idx}, {base_rem})",
                        f"b_arr_{p_idx}.assign_vector(b_rem_{p_idx}, {base_rem})",
                        f"c_arr_{p_idx}.assign_vector(c_rem_{p_idx}, {base_rem})",
                    ])
            lines.extend(["stop_timer(1)", "", "start_timer(2)"])
            for p_idx, cnt in enumerate(counts):
                lines.extend([
                    f"x_in_{p_idx} = sint.get_input_from({p_idx}, size={cnt})",
                    f"w_in_{p_idx} = sint.get_input_from({p_idx}, size={cnt})",
                    f"x_arr_{p_idx}.assign_vector(x_in_{p_idx}, 0)",
                    f"w_arr_{p_idx}.assign_vector(w_in_{p_idx}, 0)",
                ])
            lines.extend(["stop_timer(2)", "", "start_timer(3)"])
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                if full_iters > 0:
                    lines.extend([
                        f"@for_range({full_iters})",
                        f"def _beaver_mult_p{p_idx}(i):",
                        f"    base = i * {chunk}",
                        f"    x_v = x_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    w_v = w_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    a_v = a_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    b_v = b_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    c_v = c_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    d_open = (x_v - a_v).reveal()",
                        f"    e_open = (w_v - b_v).reveal()",
                        f"    prod_v = c_v + d_open * b_v + e_open * a_v + d_open * e_open",
                        f"    total_risk_acc.update(total_risk_acc + sum(prod_v))",
                    ])
                if rem > 0:
                    base_rem = full_iters * chunk
                    lines.extend([
                        f"x_rv_{p_idx} = x_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"w_rv_{p_idx} = w_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"a_rv_{p_idx} = a_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"b_rv_{p_idx} = b_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"c_rv_{p_idx} = c_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"d_ropen_{p_idx} = (x_rv_{p_idx} - a_rv_{p_idx}).reveal()",
                        f"e_ropen_{p_idx} = (w_rv_{p_idx} - b_rv_{p_idx}).reveal()",
                        f"prod_rv_{p_idx} = c_rv_{p_idx} + d_ropen_{p_idx} * b_rv_{p_idx} + e_ropen_{p_idx} * a_rv_{p_idx} + d_ropen_{p_idx} * e_ropen_{p_idx}",
                        f"total_risk_acc.update(total_risk_acc + sum(prod_rv_{p_idx}))",
                    ])
            lines.extend([
                "stop_timer(3)",
                "",
                "start_timer(4)",
                "revealed_risk = total_risk_acc.reveal()",
                'print_ln("PCC_RESULT=%s", revealed_risk)',
                'print_ln("PCC_RESULT2=0")',
                'print_ln("PCC_COUNT=%s", TOTAL_N)',
                'print_ln("PCC_TRIPLES_CONSUMED=%s", TOTAL_N)',
                "stop_timer(4)",
            ])

        elif workload == "variance":
            lines.extend(["total_sum_acc = sint(0)", "total_sq_acc = sint(0)"])
            for p_idx, cnt in enumerate(counts):
                lines.extend([
                    f"x_arr_{p_idx} = sint.Array({cnt})",
                    f"a_arr_{p_idx} = sint.Array({cnt})",
                    f"b_arr_{p_idx} = sint.Array({cnt})",
                    f"c_arr_{p_idx} = sint.Array({cnt})",
                ])
            lines.append("start_timer(1)")
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                if full_iters > 0:
                    lines.extend([
                        f"@for_range({full_iters})",
                        f"def _prep_p{p_idx}(i):",
                        f"    base = i * {chunk}",
                        f"    a_v, b_v, c_v = sint.get_random_triple(size={chunk})",
                        f"    a_arr_{p_idx}.assign_vector(a_v, base)",
                        f"    b_arr_{p_idx}.assign_vector(b_v, base)",
                        f"    c_arr_{p_idx}.assign_vector(c_v, base)",
                    ])
                if rem > 0:
                    base_rem = full_iters * chunk
                    lines.extend([
                        f"a_rem_{p_idx}, b_rem_{p_idx}, c_rem_{p_idx} = sint.get_random_triple(size={rem})",
                        f"a_arr_{p_idx}.assign_vector(a_rem_{p_idx}, {base_rem})",
                        f"b_arr_{p_idx}.assign_vector(b_rem_{p_idx}, {base_rem})",
                        f"c_arr_{p_idx}.assign_vector(c_rem_{p_idx}, {base_rem})",
                    ])
            lines.extend(["stop_timer(1)", "", "start_timer(2)"])
            for p_idx, cnt in enumerate(counts):
                lines.extend([
                    f"x_in_{p_idx} = sint.get_input_from({p_idx}, size={cnt})",
                    f"x_arr_{p_idx}.assign_vector(x_in_{p_idx}, 0)",
                ])
            lines.extend(["stop_timer(2)", "", "start_timer(3)"])
            for p_idx, cnt in enumerate(counts):
                full_iters = cnt // chunk
                rem = cnt % chunk
                if full_iters > 0:
                    lines.extend([
                        f"@for_range({full_iters})",
                        f"def _var_sq_p{p_idx}(i):",
                        f"    base = i * {chunk}",
                        f"    x_v = x_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    a_v = a_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    b_v = b_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    c_v = c_arr_{p_idx}.get_vector(base, {chunk})",
                        f"    d_open = (x_v - a_v).reveal()",
                        f"    e_open = (x_v - b_v).reveal()",
                        f"    sq_v = c_v + d_open * b_v + e_open * a_v + d_open * e_open",
                        f"    total_sum_acc.update(total_sum_acc + sum(x_v))",
                        f"    total_sq_acc.update(total_sq_acc + sum(sq_v))",
                    ])
                if rem > 0:
                    base_rem = full_iters * chunk
                    lines.extend([
                        f"x_rv_{p_idx} = x_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"a_rv_{p_idx} = a_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"b_rv_{p_idx} = b_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"c_rv_{p_idx} = c_arr_{p_idx}.get_vector({base_rem}, {rem})",
                        f"d_ropen_{p_idx} = (x_rv_{p_idx} - a_rv_{p_idx}).reveal()",
                        f"e_ropen_{p_idx} = (x_rv_{p_idx} - b_rv_{p_idx}).reveal()",
                        f"sq_rv_{p_idx} = c_rv_{p_idx} + d_ropen_{p_idx} * b_rv_{p_idx} + e_ropen_{p_idx} * a_rv_{p_idx} + d_ropen_{p_idx} * e_ropen_{p_idx}",
                        f"total_sum_acc.update(total_sum_acc + sum(x_rv_{p_idx}))",
                        f"total_sq_acc.update(total_sq_acc + sum(sq_rv_{p_idx}))",
                    ])
            lines.extend([
                "stop_timer(3)",
                "",
                "start_timer(4)",
                "rev_sum = total_sum_acc.reveal()",
                "rev_sq = total_sq_acc.reveal()",
                'print_ln("PCC_RESULT=%s", rev_sum)',
                'print_ln("PCC_RESULT2=%s", rev_sq)',
                'print_ln("PCC_COUNT=%s", TOTAL_N)',
                'print_ln("PCC_TRIPLES_CONSUMED=%s", TOTAL_N)',
                "stop_timer(4)",
            ])
        else:
            raise ValueError(f"Unsupported SMPC workload '{workload}'")

        return "\n".join(lines) + "\n"

    def compile_and_package(
        self,
        compile_dir: Path,
        counts: List[int],
        spec: SMPCProtocolSpec,
        workload: str,
    ) -> Dict[str, Any]:
        """Compiles the .mpc source and packages Programs/Bytecode + Schedules into base64."""
        src = self.generate_mpc_source(counts=counts, workload=workload)
        key_str = f"{workload}_{'_'.join(str(c) for c in counts)}_{'_'.join(spec.compiler_flags)}"
        src_hash = hashlib.sha256(key_str.encode("utf-8")).hexdigest()[:12]
        prog_name = f"pcc_{workload}_{src_hash}"

        if key_str in self._cache:
            cached_name, compile_t, pkg_files = self._cache[key_str]
            return {
                "program_name": cached_name,
                "compile_time_s": compile_t,
                "bytecode_files": pkg_files,
                "mpc_source_sha256": sha256_short(src),
            }

        programs_src = compile_dir / "Programs" / "Source"
        programs_src.mkdir(parents=True, exist_ok=True)
        mpc_file = programs_src / f"{prog_name}.mpc"
        mpc_file.write_text(src, encoding="utf-8")

        compile_py = self.mpspdz_root / "compile.py"
        cmd = ["python3", str(compile_py)] + spec.compiler_flags + [str(mpc_file)]

        t0 = time.perf_counter()
        proc = subprocess.run(
            cmd,
            cwd=str(compile_dir),
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            text=True,
        )
        compile_time_s = time.perf_counter() - t0
        if proc.returncode != 0:
            raise RuntimeError(
                f"MP-SPDZ compilation failed for {prog_name}:\n{proc.stderr}\n{proc.stdout}"
            )

        pkg_files: Dict[str, str] = {}
        bc_dir = compile_dir / "Programs" / "Bytecode"
        sch_dir = compile_dir / "Programs" / "Schedules"
        for bc_file in sorted(bc_dir.glob(f"{prog_name}*.bc")):
            pkg_files[f"Programs/Bytecode/{bc_file.name}"] = b64_encode(bc_file.read_bytes())
        for sch_file in sorted(sch_dir.glob(f"{prog_name}*.sch")):
            pkg_files[f"Programs/Schedules/{sch_file.name}"] = b64_encode(sch_file.read_bytes())

        if not pkg_files:
            raise RuntimeError(f"No compiled bytecode/schedule files found for {prog_name}")

        self._cache[key_str] = (prog_name, compile_time_s, pkg_files)
        return {
            "program_name": prog_name,
            "compile_time_s": compile_time_s,
            "bytecode_files": pkg_files,
            "mpc_source_sha256": sha256_short(src),
        }

    @staticmethod
    def parse_party_logs(
        party_stdout: Dict[int, str],
        party_stderr: Dict[int, str],
        compile_time_s: float,
        wall_time_s: float,
    ) -> Dict[str, Any]:
        """Extracts phase timers, network traffic, rounds, and outputs from 3-party MP-SPDZ logs."""
        p0_out = party_stdout.get(0, "")
        m_res = re.search(r"PCC_RESULT=(-?\d+)", p0_out)
        m_res2 = re.search(r"PCC_RESULT2=(-?\d+)", p0_out)
        m_cnt = re.search(r"PCC_COUNT=(\d+)", p0_out)
        m_triples = re.search(r"PCC_TRIPLES_CONSUMED=(\d+)", p0_out)
        if not m_res or not m_cnt:
            raise RuntimeError(f"Missing PCC_RESULT/PCC_COUNT in P0 output:\n{p0_out[-800:]}")

        result1 = int(m_res.group(1))
        result2 = int(m_res2.group(1)) if m_res2 else 0
        total_count = int(m_cnt.group(1))
        triples_consumed = int(m_triples.group(1)) if m_triples else 0

        p0_err = party_stderr.get(0, "")
        timers: Dict[int, float] = {}
        timer_bytes: Dict[int, float] = {}
        timer_rounds: Dict[int, int] = {}

        for m in re.finditer(
            r"Stopped timer\s+(\d+)\s+at\s+([0-9eE.+\-]+)\s*\(([0-9eE.+\-]+)\s*MB,\s*(\d+)\s*rounds",
            p0_err,
        ):
            tid = int(m.group(1))
            timers[tid] = float(m.group(2))
            timer_bytes[tid] = float(m.group(3)) * 1_000_000.0
            timer_rounds[tid] = int(m.group(4))

        for m in re.finditer(r"Time(\d+)\s*=\s*([0-9eE.+\-]+)", p0_err):
            tid = int(m.group(1))
            if tid not in timers:
                timers[tid] = float(m.group(2))

        t_prep = max(0.0, timers.get(1, 0.0))
        t_share = max(0.0, timers.get(2, 0.0))
        t_comp = max(0.0, timers.get(3, 0.0))
        t_recon = max(0.0, timers.get(4, 0.0))
        if (t_prep + t_share + t_comp + t_recon) == 0.0:
            t_comp = wall_time_s

        party_bytes: Dict[int, int] = {}
        for p_idx, err_text in party_stderr.items():
            mb_matches = re.findall(r"Data sent\s*=\s*([0-9eE.+\-]+)\s*MB", err_text)
            if mb_matches:
                party_bytes[p_idx] = int(round(float(mb_matches[-1]) * 1_000_000.0))
            else:
                party_bytes[p_idx] = 0

        global_match = re.search(
            r"Global data sent\s*=\s*([0-9eE.+\-]+)\s*MB\s*\(all parties\)", p0_err
        )
        if global_match:
            global_bytes = int(round(float(global_match.group(1)) * 1_000_000.0))
        else:
            global_bytes = sum(party_bytes.values())

        total_rounds = sum(timer_rounds.values())
        if total_rounds == 0:
            r_matches = re.findall(r"(\d+)\s*rounds", p0_err)
            if r_matches:
                total_rounds = sum(int(x) for x in r_matches)

        return {
            "result1": result1,
            "result2": result2,
            "total_count": total_count,
            "triples_consumed": triples_consumed,
            "compile_time_s": round(compile_time_s, 6),
            "preprocessing_time_s": round(t_prep, 6),
            "input_sharing_time_s": round(t_share, 6),
            "online_computation_time_s": round(t_comp, 6),
            "output_reconstruction_time_s": round(t_recon, 6),
            "online_total_time_s": round(t_share + t_comp + t_recon, 6),
            "total_execution_time_s": round(wall_time_s, 6),
            "party_bytes_sent": party_bytes,
            "global_network_bytes_sent": global_bytes,
            "communication_rounds": total_rounds,
        }
